package vn.vnpay.qr.wallet.qr;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.time.format.DateTimeParseException;
import java.time.format.ResolverStyle;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Set;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Component;
import vn.vnpay.qr.common.error.ApiException;
import vn.vnpay.qr.common.qr.Crc16;

@Component
public class PaymentQrParser {
    private static final Set<String> REQUIRED = Set.of("00", "01", "26", "52", "53", "54", "58", "59", "60", "62", "63");
    private static final DateTimeFormatter DATE = DateTimeFormatter.ofPattern("uuuuMMddHHmm")
            .withResolverStyle(ResolverStyle.STRICT);

    public ScannedQr parse(String qr) {
        if (qr == null || qr.isBlank() || qr.length() > 512 || qr.codePoints().anyMatch(cp ->
                Character.isISOControl(cp) || cp >= 0xD800 && cp <= 0xDFFF)) {
            throw invalid();
        }
        var tags = parseTlv(qr);
        if (!tags.keySet().containsAll(REQUIRED) || !"63".equals(tags.lastEntry().getKey()) || !qr.startsWith("000201")
                || !qr.substring(qr.length() - 8).startsWith("6304")
                || !tags.get("63").matches("[0-9A-Fa-f]{4}")) {
            throw invalid();
        }
        var merchant = parseTlv(tags.get("26"));
        var additional = parseTlv(tags.get("62"));
        if (!"01".equals(tags.get("00")) || !"12".equals(tags.get("01"))
                || !"704".equals(tags.get("53")) || !"VN".equals(tags.get("58"))
                || !tags.get("52").matches("[0-9]{4}")
                || !"A000000775".equals(merchant.get("00"))
                || !merchant.getOrDefault("01", "").matches("[A-Za-z0-9]{1,13}")
                || !validText(tags.get("59"), 25) || !validText(tags.get("60"), 15)
                || !"M".equals(additional.get("09"))
                || !additional.getOrDefault("08", "").matches("[A-Za-z0-9 ]{1,19}")
                || additional.get("08").isBlank()
                || !tags.get("54").matches("[0-9]{1,13}")) {
            throw invalid();
        }
        String ref = reference(additional.get("05"));
        if (!Crc16.calculate(qr.substring(0, qr.length() - 4)).equalsIgnoreCase(tags.get("63"))) {
            throw new ApiException(HttpStatus.UNPROCESSABLE_ENTITY, "CRC_MISMATCH", "QR CRC does not match");
        }
        return new ScannedQr(ref, Long.parseLong(tags.get("54")));
    }

    private LinkedHashMap<String, String> parseTlv(String input) {
        var result = new LinkedHashMap<String, String>();
        for (int position = 0; position < input.length();) {
            if (input.length() - position < 4) throw invalid();
            String tag = input.substring(position, position + 2);
            String lengthText = input.substring(position + 2, position + 4);
            if (!tag.matches("[0-9]{2}") || !lengthText.matches("[0-9]{2}")) throw invalid();
            int length = Integer.parseInt(lengthText);
            int start = position + 4;
            if (length == 0 || input.codePointCount(start, input.length()) < length) throw invalid();
            int end = input.offsetByCodePoints(start, length);
            if (result.putIfAbsent(tag, input.substring(start, end)) != null) throw invalid();
            position = end;
        }
        return result;
    }

    private String reference(String value) {
        // Prefix 01 + ten timestamp characters + the TX/eight-digit reference generated by B2.
        if (value == null || value.length() != 22 || !value.startsWith("01")
                || !value.substring(2, 12).matches("[0-9]{10}")
                || !value.substring(12).matches("TX[0-9]{8}")) throw invalid();
        try {
            LocalDateTime.parse("20" + value.substring(2, 12), DATE);
        } catch (DateTimeParseException ex) {
            throw invalid();
        }
        return value.substring(12);
    }

    private boolean validText(String value, int max) {
        return !value.isBlank() && value.codePointCount(0, value.length()) <= max;
    }

    private static ApiException invalid() {
        return new ApiException(HttpStatus.UNPROCESSABLE_ENTITY, "INVALID_QR", "Invalid payment QR structure or fields");
    }
}
