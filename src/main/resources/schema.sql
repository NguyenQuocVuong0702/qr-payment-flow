CREATE SEQUENCE IF NOT EXISTS merchant_order_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS wallet_user (
    user_id VARCHAR(32) PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    account_no VARCHAR(32) NOT NULL,
    pin_hash VARCHAR(60) NOT NULL,
    failed_pin_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_pin_attempts BETWEEN 0 AND 3),
    pin_locked_until TIMESTAMP(6) WITH TIME ZONE,
    version BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS account (
    account_no VARCHAR(32) PRIMARY KEY,
    owner_name VARCHAR(100) NOT NULL,
    balance BIGINT NOT NULL CHECK (balance >= 0),
    version BIGINT NOT NULL
);
CREATE SEQUENCE IF NOT EXISTS bank_ref_seq START WITH 1 INCREMENT BY 1 NO CYCLE;
CREATE TABLE IF NOT EXISTS idempotency (
    request_id UUID PRIMARY KEY,
    txn_ref VARCHAR(10) NOT NULL,
    payer_account VARCHAR(32) NOT NULL,
    amount BIGINT NOT NULL CHECK (amount BETWEEN 1000 AND 500000000),
    http_status INTEGER,
    response_body CLOB,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL,
    CONSTRAINT ck_idempotency_result CHECK ((http_status IS NULL AND response_body IS NULL)
        OR (http_status IS NOT NULL AND http_status BETWEEN 200 AND 599 AND response_body IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS orders (
    order_id VARCHAR(32) PRIMARY KEY,
    merchant_id VARCHAR(32) NOT NULL,
    amount BIGINT NOT NULL,
    description VARCHAR(19) NOT NULL,
    status VARCHAR(24) NOT NULL,
    txn_ref VARCHAR(32),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    paid_at TIMESTAMP(6) WITH TIME ZONE,
    version BIGINT NOT NULL,
    CONSTRAINT uk_orders_txn_ref UNIQUE (txn_ref),
    CONSTRAINT ck_orders_amount CHECK (amount BETWEEN 1000 AND 500000000),
    CONSTRAINT ck_orders_description CHECK (
        CHAR_LENGTH(TRIM(description)) > 0 AND NOT REGEXP_LIKE(description, '[^A-Za-z0-9 ]')),
    CONSTRAINT ck_orders_status CHECK (
        status IN ('CREATED', 'WAITING_PAYMENT', 'PAID', 'PAYMENT_FAILED', 'EXPIRED'))
);

CREATE TABLE IF NOT EXISTS merchant (
    merchant_id VARCHAR(13) PRIMARY KEY,
    name VARCHAR(25) NOT NULL,
    city VARCHAR(15) NOT NULL,
    mcc VARCHAR(4) NOT NULL,
    secret_key VARCHAR(128) NOT NULL,
    ipn_url VARCHAR(255) NOT NULL,
    account_no VARCHAR(32) NOT NULL
);

-- Fixed TX + eight digits keeps 62/05 within the original Type 04 limit of 25 characters.
CREATE SEQUENCE IF NOT EXISTS gateway_txn_seq START WITH 1 INCREMENT BY 1 MAXVALUE 99999999 NO CYCLE;

CREATE TABLE IF NOT EXISTS payment_txn (
    txn_ref VARCHAR(10) PRIMARY KEY,
    merchant_id VARCHAR(13) NOT NULL,
    order_id VARCHAR(32) NOT NULL,
    amount BIGINT NOT NULL,
    description VARCHAR(19) NOT NULL,
    status VARCHAR(24) NOT NULL,
    qr_string VARCHAR(512) NOT NULL,
    expire_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    payer_account VARCHAR(32),
    bank_ref VARCHAR(32),
    fail_reason VARCHAR(64),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    paid_at TIMESTAMP(6) WITH TIME ZONE,
    version BIGINT NOT NULL,
    CONSTRAINT fk_payment_merchant FOREIGN KEY (merchant_id) REFERENCES merchant(merchant_id),
    CONSTRAINT uk_payment_order UNIQUE (merchant_id, order_id),
    CONSTRAINT uk_payment_bank_ref UNIQUE (bank_ref),
    CONSTRAINT ck_payment_amount CHECK (amount BETWEEN 1000 AND 500000000),
    CONSTRAINT ck_payment_description CHECK (
        CHAR_LENGTH(TRIM(description)) > 0 AND NOT REGEXP_LIKE(description, '[^A-Za-z0-9 ]')),
    CONSTRAINT ck_payment_status CHECK (
        status IN ('PENDING', 'PROCESSING', 'SUCCESS', 'FAILED', 'EXPIRED', 'REFUNDED')),
    CONSTRAINT ck_payment_expiry CHECK (expire_at > created_at)
);

CREATE TABLE IF NOT EXISTS ledger_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_ref VARCHAR(10) NOT NULL REFERENCES payment_txn(txn_ref),
    bank_ref VARCHAR(32) NOT NULL,
    account_no VARCHAR(32) NOT NULL REFERENCES account(account_no),
    direction VARCHAR(6) NOT NULL CHECK (direction IN ('DEBIT','CREDIT')),
    amount BIGINT NOT NULL CHECK (amount > 0),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_ledger_bank_direction UNIQUE(bank_ref,direction),
    CONSTRAINT uk_ledger_txn_direction UNIQUE(txn_ref,direction)
);
